export function zbaht(n: number) {
  return "฿" + Number(n || 0).toLocaleString("th-TH");
}

/** "1 ชม. 20 นาที" from minutes. */
export function hm(min: number) {
  min = Math.round(Number(min) || 0);
  const h = Math.floor(min / 60), m = min % 60;
  return h ? `${h} ชม.${m ? ` ${m} นาที` : ""}` : `${m} นาที`;
}

export function zdate(d: Date | string | null | undefined, time = false) {
  if (!d) return "";
  const x = new Date(d);
  const s = x.toLocaleDateString("th-TH", { day: "numeric", month: "short", year: "2-digit", timeZone: "Asia/Bangkok" });
  return time ? `${s} ${x.toLocaleTimeString("th-TH", { hour: "2-digit", minute: "2-digit", timeZone: "Asia/Bangkok" })}` : s;
}
